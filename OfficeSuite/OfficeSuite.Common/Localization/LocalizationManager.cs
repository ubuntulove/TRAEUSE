        public string GetString(string key)
        {
            if (_translations.TryGetValue(_currentLanguage, out var languageStrings))
            {
                if (languageStrings.TryGetValue(key, out var translation))
                {
                    return translation;
                }
            }

            if (_translations.TryGetValue("en-US", out var defaultStrings))
            {
                if (defaultStrings.TryGetValue(key, out var defaultTranslation))
                {
                    return defaultTranslation;
                }
            }

            return key;
        }

